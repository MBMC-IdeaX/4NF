// Helper to query all active buses across all routes
export function getAllBuses() {
  const list = [];
  for (const r of VALLEY_ROUTES) {
    for (const b of r.buses) {
      list.push({ ...b, routeId: r.id, routeNumber: r.number, from: r.from, to: r.to });
    }
  }
  return list;
}

// Helper to search routes by station query
export function findRoutesByStation(query) {
  if (!query || !query.trim()) return VALLEY_ROUTES;
  const q = query.toLowerCase().trim();
  return VALLEY_ROUTES.filter((r) => {
    return (
      r.from.toLowerCase().includes(q) ||
      r.to.toLowerCase().includes(q) ||
      r.fromNe.includes(q) ||
      r.toNe.includes(q) ||
      r.stops.some((s) => s.name.toLowerCase().includes(q) || s.ne.includes(q))
    );
  });
}
